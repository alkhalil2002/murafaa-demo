export type NajizMainClass = keyof typeof NAJIZ;

/** Flatten to (main, sub, caseType) leaf rows — used to seed the reference table. */
export function najizLeaves(): Array<{ mainClass: string; subClass: string; caseType: string }> {
  const rows: Array<{ mainClass: string; subClass: string; caseType: string }> = [];
  for (const [mainClass, subs] of Object.entries(NAJIZ)) {
    for (const [subClass, types] of Object.entries(subs)) {
      for (const caseType of types) rows.push({ mainClass, subClass, caseType });
    }
  }
  return rows;
}
